use std::io::Write;
use std::path::Path;
use std::process::{Command, Stdio};

fn formatted(source: &str, tokens: proc_macro2::TokenStream) -> String {
    let mut formatter = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::inherit())
        .spawn()
        .expect("rustfmt from the repository toolchain");
    write!(formatter.stdin.take().unwrap(), "{}", tokens).unwrap();
    let output = formatter
        .wait_with_output()
        .expect("format generated operations");
    assert!(output.status.success(), "rustfmt failed");
    format!(
        "// Generated by bun run gen:operations. Edit {source} instead.\n{}",
        String::from_utf8(output.stdout).unwrap()
    )
}

fn main() {
    let check = match std::env::args().nth(1).as_deref() {
        None => false,
        Some("--check") => true,
        _ => panic!("usage: gen-operations [--check]"),
    };
    let domains = operations::catalog();
    operations::validate(&domains).expect("valid operation catalog");
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/wasm_client/generated");
    let mut artifacts: Vec<(&str, String, proc_macro2::TokenStream)> = domains
        .iter()
        .map(|domain| {
            (
                domain.name,
                format!("codegen/src/operations/{}.rs", domain.name),
                operations::emit(domain),
            )
        })
        .collect();
    artifacts.push(("storage", "codegen/src/storage.rs".into(), storage::emit()));
    artifacts.push((
        "diagnostics",
        "codegen/src/diagnostics.rs".into(),
        diagnostics::emit(),
    ));
    artifacts.push((
        "nodes",
        "codegen/src/node_projection.rs".into(),
        node_projection::emit(),
    ));
    artifacts.push((
        "call_adapters",
        "codegen/src/call_adapters.rs".into(),
        call_adapters::emit(),
    ));
    artifacts.push((
        "host_callbacks",
        "codegen/src/host_callbacks.rs".into(),
        host_callbacks::emit(),
    ));
    artifacts.push((
        "preparations",
        "codegen/src/preparations.rs".into(),
        preparations::emit_helpers(),
    ));
    artifacts.push(("events", "codegen/src/events.rs".into(), events::emit()));
    artifacts.push((
        "teardown",
        "codegen/src/lifecycle.rs".into(),
        lifecycle::emit(),
    ));
    artifacts.push((
        "storage_crud",
        "codegen/src/storage_crud.rs".into(),
        proc_macro2::TokenStream::new(),
    ));
    artifacts.push((
        "projections",
        "codegen/src/projections.rs".into(),
        projections::emit(),
    ));
    artifacts.push((
        "variant_strings",
        "codegen/src/variants.rs".into(),
        variants::root(),
    ));
    artifacts.push((
        "variant_projections",
        "codegen/src/variants.rs".into(),
        variants::projections(),
    ));
    let mut names = std::collections::BTreeSet::new();
    for (name, source, _) in &artifacts {
        assert!(names.insert(name), "duplicate generated artifact");
        assert!(
            Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("..")
                .join(source)
                .is_file(),
            "generated artifact source does not exist: {source}"
        );
    }
    if check {
        let expected: std::collections::BTreeSet<_> = artifacts
            .iter()
            .map(|(name, _, _)| format!("{name}.rs"))
            .collect();
        let actual: std::collections::BTreeSet<_> = std::fs::read_dir(&root)
            .expect("generated directory")
            .map(|entry| {
                entry
                    .unwrap()
                    .file_name()
                    .into_string()
                    .expect("UTF-8 generated filename")
            })
            .collect();
        assert_eq!(actual, expected, "generated operation inventory drifted");
    }
    for (name, source, tokens) in artifacts {
        let path = root.join(format!("{name}.rs"));
        let contents = if name == "storage_crud" {
            let contents = storage_crud::readable(|tokens| {
                formatted("", tokens).split_once('\n').unwrap().1.to_owned()
            });
            format!("// Generated by bun run gen:operations. Edit {source} instead.\n{contents}")
        } else {
            formatted(&source, tokens)
        };
        if check {
            assert_eq!(
                std::fs::read_to_string(&path).expect("generated file"),
                contents,
                "generated operations drifted: {}",
                path.display()
            );
        } else {
            std::fs::create_dir_all(&root).unwrap();
            std::fs::write(path, contents).unwrap();
        }
    }
}
